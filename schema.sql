-- 1. Bảng người dùng (users)
create table if not exists users (
    id bigint generated by default as identity primary key,
    username text unique not null,
    password text not null,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Tạo sẵn tài khoản mặc định vinh / 123456 nếu chưa có
insert into users (username, password)
values ('vinh', '123456')
on conflict (username) do nothing;

-- 2. Bảng đợt bán hàng (sales_batches)
create table if not exists sales_batches (
    id bigint generated by default as identity primary key,
    user_id bigint references users(id) on delete cascade not null,
    name text not null,
    status text not null default 'active', -- 'active': đang mở bán, 'closed': đã kết thúc
    created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Tạo đợt bán mặc định cho tài khoản vinh nếu chưa có
insert into sales_batches (user_id, name, status)
select id, 'Đợt mở bán đầu tiên', 'active' 
from users 
where username = 'vinh'
and not exists (select 1 from sales_batches where user_id = users.id);

-- 3. Bảng mặt hàng / thực đơn (products)
create table if not exists products (
    id bigint generated by default as identity primary key,
    user_id bigint references users(id) on delete cascade,
    batch_id bigint references sales_batches(id) on delete cascade,
    name text not null,
    price numeric not null default 0,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Nếu bảng products đã có từ trước, thêm các cột cần thiết
alter table products add column if not exists user_id bigint references users(id) on delete cascade;
alter table products add column if not exists batch_id bigint references sales_batches(id) on delete cascade;

-- 4. Bảng đơn hàng (orders)
create table if not exists orders (
    id bigint generated by default as identity primary key,
    user_id bigint references users(id) on delete cascade,
    batch_id bigint references sales_batches(id) on delete cascade,
    customer_name text default '',
    customer_phone text not null,
    shipping_address text not null,
    shipping_fee numeric not null default 0,
    status text not null default 'Chờ xử lý',
    total_amount numeric not null default 0,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Nếu bảng orders đã tạo trước đó, bổ sung các cột mới nếu thiếu
alter table orders add column if not exists user_id bigint references users(id) on delete cascade;
alter table orders add column if not exists batch_id bigint references sales_batches(id) on delete cascade;
alter table orders add column if not exists shipping_fee numeric not null default 0;
alter table orders add column if not exists customer_name text default '';

-- 5. Bảng chi tiết đơn hàng (order_items)
create table if not exists order_items (
    id bigint generated by default as identity primary key,
    order_id bigint references orders(id) on delete cascade not null,
    product_id bigint references products(id) on delete set null,
    product_name text not null,
    price numeric not null default 0,
    quantity int not null default 1
);

-- 6. Di chuyển dữ liệu cũ:
-- Gán user_id cho các bản ghi cũ về tài khoản 'vinh'
update products 
set user_id = (select id from users where username = 'vinh' limit 1) 
where user_id is null;

update orders 
set user_id = (select id from users where username = 'vinh' limit 1) 
where user_id is null;

-- Gán batch_id cho các mặt hàng và đơn hàng cũ chưa có đợt bán
update products 
set batch_id = (select id from sales_batches where user_id = products.user_id order by id asc limit 1)
where batch_id is null;

update orders 
set batch_id = (select id from sales_batches where user_id = orders.user_id order by id asc limit 1)
where batch_id is null;

-- 7. Mở quyền truy cập cho Row Level Security (RLS)
alter table users enable row level security;
alter table sales_batches enable row level security;
alter table products enable row level security;
alter table orders enable row level security;
alter table order_items enable row level security;

create policy "Cho phép toàn quyền users" on users for all using (true) with check (true);
create policy "Cho phép toàn quyền sales_batches" on sales_batches for all using (true) with check (true);
create policy "Cho phép toàn quyền products" on products for all using (true) with check (true);
create policy "Cho phép toàn quyền orders" on orders for all using (true) with check (true);
create policy "Cho phép toàn quyền order_items" on order_items for all using (true) with check (true);
